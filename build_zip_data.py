"""Rebuild data/zip-data.js from the `zipcodes` Python package.

Usage:
    pip install zipcodes
    python scripts/build_zip_data.py          # California (default)
    python scripts/build_zip_data.py CA NV AZ # more than one state
"""
import json, sys, pathlib
from collections import defaultdict
import zipcodes

states = [s.upper() for s in sys.argv[1:]] or ["CA"]
rows = [z for s in states for z in zipcodes.filter_by(state=s) if z["lat"] and z["active"]]

cities = sorted({z["city"] for z in rows})
counties = sorted({z["county"].replace(" County", "") for z in rows})
ci = {c: i for i, c in enumerate(cities)}
co = {c: i for i, c in enumerate(counties)}

data = {
    "c": cities,
    "k": counties,
    "z": {z["zip_code"]: [round(float(z["lat"]), 3), round(float(z["long"]), 3),
                          ci[z["city"]], co[z["county"].replace(" County", "")]] for z in rows},
}
alias = defaultdict(list)
for z in rows:
    for a in z["acceptable_cities"]:
        if a != z["city"] and len(a) > 3:
            alias[a].append(z["zip_code"])
data["a"] = alias

out = pathlib.Path(__file__).resolve().parent.parent / "data" / "zip-data.js"
out.write_text("// ZIP code centers. Generated by scripts/build_zip_data.py — don't edit by hand.\n"
               "window.ZIPDATA=" + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"Wrote {len(data['z'])} ZIP codes for {', '.join(states)} to {out}")
